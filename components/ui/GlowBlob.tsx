//
// این کامپوننت کاملاً نمایشی و بدون‌تعامل است (`pointerEvents="none"`) — هرگز جلوی لمسِ
// عناصر زیرش را نمی‌گیرد.
//
// **پولیشِ کیفیت (درخواستِ کارفرما — «یه چیز درجه‌یک»، بدون افزودن کتابخانه‌ی تازه):** قبلاً
// این جلوه فقط ۳ لایه‌ی ثابت داشت — با فاصله‌های نسبتاً بزرگ بین لایه‌ها (۰٪/۱۸٪/۳۶٪ این‌ست)،
// که از نزدیک کمی «پله‌پله» (Banding) به‌نظر می‌رسید، نه یک محوشدگیِ واقعاً نرم. حالا تعدادِ
// لایه‌ها به یک prop اختیاری تبدیل شد (پیش‌فرض ۶ لایه به‌جای ۳) و منحنیِ شفافیت هم نرم‌تر و
// تصاعدی‌تر محاسبه می‌شود — نتیجه یک محوشدگیِ به‌مراتب پیوسته‌تر و نزدیک‌تر به یک بلورِ واقعی،
// هنوز هم بدون هیچ وابستگیِ تازه یا نیاز به Rebuild.
import { View } from 'react-native';

export function GlowBlob({
  size,
  color,
  opacity = 0.35,
  layers = 6,
  style,
}: {
  // قطرِ دایره‌ی بیرونی (بزرگ‌ترین لایه) بر حسب dp.
  size: number;
  // رنگِ پایه به‌صورت hex (مثل Colors.primary) — خودِ کامپوننت شفافیتِ هر لایه را جدا محاسبه می‌کند.
  color: string;
  // شفافیتِ لایه‌ی هسته/مرکزی (پررنگ‌ترین). لایه‌های بیرونی‌تر خودکار کم‌رنگ‌تر می‌شوند.
  opacity?: number;
  // تعدادِ حلقه‌های هم‌مرکز — بیشتر یعنی محوشدگیِ نرم‌تر (پیش‌فرض ۶ برای بیشترِ موارد کافی است؛
  // برای هاله‌های خیلی بزرگ می‌توان ۸ داد، برای هاله‌های خیلی کوچک ۴ کافی است).
  layers?: number;
  // موقعیت‌دهیِ مطلق (top/left/right/bottom) — از بیرون پاس داده می‌شود.
  style?: object;
}) {
  const toRgba = (hex: string, a: number) => {
    const clean = hex.replace('#', '');
    const r = parseInt(clean.substring(0, 2), 16);
    const g = parseInt(clean.substring(2, 4), 16);
    const b = parseInt(clean.substring(4, 6), 16);
    return `rgba(${r},${g},${b},${a})`;
  };

  const safeLayers = Math.max(2, layers);

  // لایه‌ی i=0 بزرگ‌ترین/کم‌رنگ‌ترین (بیرونی‌ترین) است؛ لایه‌ی آخر کوچک‌ترین/پررنگ‌ترین (هسته).
  // فاصله‌ی هر لایه از لبه (inset) با یک منحنیِ درجه‌دوم (t^1.6) رشد می‌کند — نه خطی — تا لایه‌های
  // نزدیکِ مرکز فشرده‌تر و لایه‌های بیرونی پراکنده‌تر باشند، دقیقاً همان توزیعی که یک بلورِ
  // گاوسیِ واقعی دارد (بیشترِ چگالیِ نور نزدیکِ مرکز است).
  const ringInsets = Array.from({ length: safeLayers }, (_, i) => {
    const t = i / (safeLayers - 1); // 0 (بیرونی‌ترین) تا 1 (مرکز)
    return (t ** 1.6) * size * 0.46;
  });

  return (
    <View pointerEvents="none" style={[{ width: size, height: size }, style]}>
      {ringInsets.map((inset, i) => {
        const t = i / (safeLayers - 1);
        // شفافیت هم با همون منطقِ تصاعدی رشد می‌کند: لایه‌ی بیرونی حدودِ ۲۰٪ شفافیتِ پایه،
        // لایه‌ی مرکزی تا ۱٫۸ برابرِ شفافیتِ پایه (سقف ۰٫۹۵ تا هیچ‌وقت کاملاً تخت نشود).
        const layerOpacity = Math.min(opacity * (0.2 + t * 1.6), 0.95);
        return (
          <View
            key={i}
            style={{
              position: 'absolute',
              top: inset,
              left: inset,
              right: inset,
              bottom: inset,
              borderRadius: size / 2,
              backgroundColor: toRgba(color, layerOpacity),
            }}
          />
        );
      })}
    </View>
  );
}